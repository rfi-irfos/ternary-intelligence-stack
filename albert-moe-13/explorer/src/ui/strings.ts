export const STRINGS: Record<Lang, Record<StringKey, Entry>> = { en: EN, de: DE };

/** Resolves an entry for a mode. */
export const resolve = (e: Entry, mode: Mode): string => (typeof e === 'string' ? e : e[mode]);

/** Fills {name} placeholders. Unknown names stay as written. */
export function fill(s: string, vars: Record<string, string | number> = {}): string {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** The string `key` in `lang` and `mode`, placeholders filled. */
export function tr(key: StringKey, lang: Lang, mode: Mode, vars?: Record<string, string | number>): string {
  return fill(resolve(STRINGS[lang][key], mode), vars);
}
