/**
 * Every UI string, in both languages. An entry is either one string (same in Simple and Advanced) or
 * `{ simple, advanced }`: Simple uses everyday words, Advanced the technical names (the technical
 * English terms stay English in the German UI too). Placeholders like {n} are filled by `t()`.
 *
 * Long-form content (panel texts, caveats, layer steps) lives in src/content and src/layer/steps.ts as
 * { en, de } pairs and goes through the same language lookup (prefs.lt). With DE selected every visible
 * text is German; only formulas, tensor names, code ids, the model name and the traced prompts stay as
 * they are. Advanced German keeps the usual technical terms (Attention, Router, Top-k, Logits, Layer Norm).
 */

